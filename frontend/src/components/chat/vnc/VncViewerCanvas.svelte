            placeholder="VNC Server Password"
          />
        </div>
      </div>
      <button
        on:click={connect}
        class="mt-4 w-full bg-theme-primry hover:bg-indigo-700 text-white font-bold py-2 px-4 rounded-md dark:bg-gray-900 dark:border-gray-800 focus:outline-none focus:ring-2 focus:ring-indigo-500 focus:ring-opacity-50 transition duration-150 ease-in-out"
      >
        Connect
      </button>
    </div>
  {/if}

  <div class="status-and-controls mt-2 mb-2 flex justify-between items-center">
    <p class="text-sm text-gray-600 flex-grow">
      Status: <span class="font-semibold">{connectionStatus}</span>
    </p>
    <button
      on:click={toggleSettings}
      class="ml-4 bg-gray-300 hover:bg-gray-400 text-gray-800 font-semibold py-1 px-3 rounded-md text-sm focus:outline-none focus:ring-2 focus:ring-gray-500 focus:ring-opacity-50 transition duration-150 ease-in-out"
    >
      {#if rfbInstance}Disconnect{:else}Show/Hide Settings{/if}
    </button>
  </div>

  <!-- This div is the target for the RFB canvas -->
  <div
    bind:this={screenElement}
    id="vnc-screen"
    class="vnc-screen-area w-full h-[600px] border border-gray-400 bg-black rounded-md shadow-inner relative"
  >
    <!-- RFB will inject its canvas here. -->
    <!-- You can put placeholder content here if you want. -->
    {#if !rfbInstance && !showConnectionSettings}
      <div class="flex items-center justify-center h-full">
        <p class="text-gray-400">VNC Display Area</p>
      </div>
    {/if}
  </div>
</div>

