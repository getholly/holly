<script lang="ts">
  import { onDestroy } from "svelte";
  // Ensure the path is correct based on how @novnc/novnc structures its exports.
  // It's often under `core/rfb.js` or `lib/rfb.js`.
  // If you encounter "Cannot find module" errors, double-check your node_modules/@novnc/novnc directory.

  let vncWebSocketHost: string = "localhost";
  // This should be the port where websockify is running, typically the same port as the noVNC web UI.
  let vncWebSocketPort: number = 6901;
  let vncPassword: string = "vncpassword"; // Password for the actual VNC server

  let connectionStatus: string = "Disconnected";
  let rfbInstance: RFB | null = null;
  let screenElement: HTMLDivElement; // This div will host the canvas generated by RFB

  let showConnectionSettings: boolean = true;
  let connectionError: string | null = null;

  function connect() {
    connectionError = null;
    if (!screenElement) {
      connectionError =
        "Fatal Error: Screen container element not found in the DOM.";
      connectionStatus = connectionError;
      console.error(connectionError);
      return;
    }

    if (rfbInstance) {
      disconnect(); // Disconnect any existing session first
    }

    const webSocketUrl = `ws://${vncWebSocketHost}:${vncWebSocketPort}`;
    connectionStatus = `Connecting to ${webSocketUrl}...`;
    showConnectionSettings = false;
    console.log(`Attempting to connect RFB to: ${webSocketUrl}`);

    try {
      // The `target` is the HTML element where RFB will create and manage its canvas.
      // The `url` is the WebSocket endpoint for the VNC connection (websockify).
      // `credentials` are passed to the VNC server via websockify.
      rfbInstance = new RFB(screenElement, webSocketUrl, {
        credentials: { password: vncPassword },
      });

      // --- RFB Event Listeners ---
      rfbInstance.addEventListener("connect", () => {
        connectionStatus = `Connected to VNC via ${webSocketUrl}`;
        console.log("RFB Event: connect");
        // RFB automatically manages the canvas within screenElement
        // You might want to adjust focus or styles here
        if (rfbInstance && rfbInstance.remoteFocus) {
          rfbInstance.focus();
        }
      });

      rfbInstance.addEventListener("disconnect", (event: Event) => {
        // event.detail contains { clean: boolean, reason?: string }
        const reason = event.detail.reason
          ? ` Reason: ${event.detail.reason}`
          : "";
        connectionStatus = `Disconnected.${reason} (Clean: ${event.detail.clean})`;
        console.log(
          `RFB Event: disconnect - Clean: ${event.detail.clean}, Detail:`,
          event.detail,
        );
        rfbInstance = null; // Clear the instance
        // Do not set showConnectionSettings = true here, allow user to see disconnect message
        // User can click "Disconnect" button (which becomes "Show Settings") to go back
      });

      rfbInstance.addEventListener("credentialsrequired", () => {
        connectionStatus = "VNC server requires credentials.";
        console.log("RFB Event: credentialsrequired");
        // This typically means the password was wrong or not provided,
        // and the server is prompting again (though RFB usually handles the initial password).
        // You might want to prompt the user for password again if this happens.
        if (rfbInstance) {
          const newPassword = prompt("VNC Password Required:", vncPassword);
          if (newPassword) {
            vncPassword = newPassword; // Update the password for future attempts or if RFB allows resending
            rfbInstance.sendCredentials({ password: newPassword });
          } else {
            connectionStatus = "Credentials not provided. Disconnecting.";
            disconnect();
          }
        }
      });

      rfbInstance.addEventListener("securityfailure", (event: Event) => {
        connectionStatus = `Security failure: ${event.detail.reason || "Unknown reason"}`;
        console.error("RFB Event: securityfailure", event.detail);
        disconnect(); // Ensure cleanup
      });

      rfbInstance.addEventListener("onerror", (event: Event) => {
        // This is a more generic error handler if RFB itself encounters an issue.
        connectionStatus = `An error occurred: ${event.detail.error || "Unknown RFB error"}`;
        console.error("RFB Event: onerror", event.detail);
        // Consider if disconnect is appropriate here or if it's a non-fatal error.
      });

      // Add other event listeners as needed:
      // - 'desktopname': (event) => console.log('Desktop name:', event.detail.name)
      // - 'bell': () => console.log('VNC Bell received')
      // - 'clipboard': (event) => console.log('Clipboard from server:', event.detail.text)
    } catch (error: Event) {
      connectionError = `Failed to initialize RFB client: ${error.message}`;
      connectionStatus = connectionError;
      console.error(connectionError, error);
      showConnectionSettings = true; // Show settings again on critical init error
      rfbInstance = null;
    }
  }

  function disconnect() {
    connectionError = null;
    if (rfbInstance) {
      console.log("Disconnecting RFB instance...");
      rfbInstance.disconnect(); // This should trigger the 'disconnect' event listener
      rfbInstance = null; // Explicitly nullify
    }
    // Reset status, but wait for the disconnect event to confirm for a cleaner UX
    // connectionStatus = 'Disconnected';
    // showConnectionSettings = true; // This is handled by the "Show Settings / Disconnect" button logic now
  }

  function toggleSettings() {
    if (rfbInstance) {
      // If connected, this button acts as "Disconnect"
      disconnect();
      // The disconnect event will update status. We want to show settings after disconnect.
      // A small delay might be needed if the disconnect event is asynchronous and we want to ensure it fires first.
      setTimeout(() => {
        showConnectionSettings = true;
        connectionStatus = "Disconnected. Configure and connect again.";
      }, 100); // Give a moment for disconnect event processing
    } else {
      // If not connected, this button shows settings (or hides if already shown, though not the primary use)
      showConnectionSettings = !showConnectionSettings;
      if (!showConnectionSettings && !rfbInstance) {
        connectionStatus =
          'Connection panel hidden. Click "Connect" in settings.';
      } else {
        connectionStatus = "Disconnected. Configure and connect again.";
      }
    }
  }

  // Ensure disconnection when the component is destroyed
  onDestroy(() => {
    console.log("VncViewerCanvas: onDestroy called. Cleaning up RFB instance.");
    disconnect();
  });
</script>

<div class="vnc-canvas-container p-4">
